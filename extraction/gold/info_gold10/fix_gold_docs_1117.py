"""11/17 제출서류 정답 재검토 (원문의 서류 관련 줄 197개를 정답과 대조). 한 번만 실행
LLM 결과를 본 뒤의 재검토라 보고서에 적는다. 기준은 11/17 정예은 결정 그대로
  - 필수: "이 서류가 없으면 신청이 안 되나?" / 선택 서류는 대상에 이유
  - 택1이라도 사람마다 정해져 있으면 대상별로 나눔

추가
1. 시각장애인 안마원·안마시술소 예외 서류 2개 (업종 제외표의 "신청가능 … 징구"): 117673(최상위), 122273, 123795(컨설팅 트랙)
2. 119938 기 작성된 사업계획서 (선택, "참고자료로 추가 제출하여도 무방")
3. 123795 컨설팅: 자부담 면제(연매출 10,400만원 미만)용 부가가치세과세표준증명원 또는 면세사업자수입금액증명원 (선택)
4. 127098 기술 실시권 확보·예정 현황 증빙 ("기술이 이미 매칭된 경우 … 서류로 증빙")
나눔 (사람마다 정해짐)
5. 123795 법률구조 "사업자등록증 (일반과세자는…)" → 간이과세자 / 일반과세자
6. 123795 법률구조 "건강보험료납부확인서 또는 고지서 또는 부과내역 확인서" → 직장가입자 / 지역가입자
삭제
7. 117673 최상위 제출서류 "없음" 줄 (1번으로 최상위 서류가 생김)
"""
import csv
from pathlib import Path

G = Path(__file__).resolve().parent
F = G / "info_라벨링.csv"
rows = list(csv.DictReader(open(F, encoding="utf-8-sig")))
cols = list(rows[0].keys())
P = "PBLN_000000000"
names = {r["공고ID"]: r["공고명"] for r in rows}
MEMO = "11/17 제출서류 재검토로 수정 (원문 대조)"
T1 = "찾아가는 1:1 교육(경영애로 개선 컨설팅)"
T2 = "소상공인 무료법률구조"
BLIND = "시각장애인이 운영하는 안마원·안마시술소"


def doc(pid, 값, 필수="O", 대상="", 트랙=""):
    r = {c: "" for c in cols}
    r.update(공고ID=P + pid, 공고명=names[P + pid], 트랙=트랙, 칸="제출서류", 값=값, 필수=필수, 대상=대상, 메모=MEMO)
    return r


add = []
for pid, tr in ():  # 11/17 정예은: 안마원 예외 서류는 뺌 (업종 제외표 예외라 서류 목록으로 보지 않음)
    add += [doc(pid, "안마원 개설신고증명서 또는 안마시술소 개설신고증명서", 대상=BLIND, 트랙=tr),
            doc(pid, "임대차계약서 또는 부동산등기사항전부증명서", 대상=BLIND, 트랙=tr)]
add += [doc("119938", "기 작성된 사업계획서 (참고자료)", 필수="X", 대상="있으면 추가 제출"),
        doc("123795", "부가가치세과세표준증명원 또는 부가가치세면세사업자수입금액증명원", 필수="X",
            대상="자부담 면제받으려면 (최근 1년 연매출 10,400만원 미만)", 트랙=T1),
        doc("127098", "기술 실시권 확보·예정 현황 증빙서류", 대상="출연(연) 기술이 이미 매칭된 경우")]

out = []
for r in rows:
    pid = r["공고ID"][-6:]
    if pid == "117673" and r["칸"] == "제출서류" and r["트랙"] == "" and r["값"] == "없음":
        continue
    if pid == "123795" and r["값"].startswith("사업자등록증 (일반과세자"):
        a, b = dict(r), dict(r)
        a.update(값="간이과세용 사업자등록증", 대상="간이과세자", 메모=MEMO + ": 간이/일반과세자로 나눔")
        b.update(값="사업자등록증 및 상시근로자수 소명서류", 대상="일반과세자", 메모=MEMO + ": 간이/일반과세자로 나눔")
        out += [a, b]
        continue
    if pid == "123795" and r["값"].startswith("건강보험료납부확인서 또는"):
        a, b = dict(r), dict(r)
        a.update(값="건강보험료납부확인서", 대상="중위소득 150% 이하 증빙 시, 직장보험가입자", 메모=MEMO + ": 직장/지역가입자로 나눔")
        b.update(값="건강보험료 고지서 또는 지역보험료 부과내역 확인서", 대상="중위소득 150% 이하 증빙 시, 지역보험가입자",
                 메모=MEMO + ": 직장/지역가입자로 나눔")
        out += [a, b]
        continue
    out.append(r)

# 같은 공고의 마지막 제출서류 줄 뒤에 추가
for a in add:
    idx = max(i for i, r in enumerate(out) if r["공고ID"] == a["공고ID"] and r["칸"] == "제출서류") if any(
        r["공고ID"] == a["공고ID"] and r["칸"] == "제출서류" for r in out) else len(out) - 1
    out.insert(idx + 1, a)

with open(F, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=cols)
    w.writeheader()
    w.writerows(out)
print(f"{len(rows)}줄 → {len(out)}줄")
